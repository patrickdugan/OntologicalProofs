"""Finite controls for the quasicrystalline Logos proposal.

The spectra below are synthetic rational examples. They make no assertion
about actual zeta zeros. Equality of their projected counting measures gives
equality of their diffraction intensities at every real frequency.

The arithmetic section evaluates the cumulative signed measure from
J. Arias de Reyna, arXiv:2402.10604v2, at six finite cutoffs. These values do
not establish an asymptotic bound, temperedness, or RH. Floating-point
arithmetic is confined to the explicitly numerical sections.
"""

from __future__ import annotations

from collections import Counter
from fractions import Fraction as F
from math import cos, fsum, isclose, isqrt, log, pi, sin, sqrt
import json

Point = tuple[F, F]
Spectrum = tuple[Point, ...]
CHECKPOINTS = (10, 100, 1_000, 10_000, 100_000, 1_000_000)


def ordinate_measure(spectrum: Spectrum) -> Counter[F]:
    """Projected counting measure, with every multiplicity retained."""
    return Counter(imag for _, imag in spectrum)


def difference_measure(ordinates: Counter[F]) -> Counter[F]:
    """Exact coefficients of the finite, unnormalized autocorrelation."""
    result: Counter[F] = Counter()
    for x, mx in ordinates.items():
        for y, my in ordinates.items():
            result[x - y] += mx * my
    return result


def spectral_coordinate(point: Point) -> Point:
    """Real and imaginary parts of -i * (rho - 1/2)."""
    real, imag = point
    return imag, F(1, 2) - real


def intensity(ordinates: Counter[F], frequency: float) -> float:
    """|N^-1 sum_gamma multiplicity(gamma) exp(-2 pi i k gamma)|^2."""
    count = sum(ordinates.values())
    if count == 0:
        raise ValueError("a normalized intensity needs a nonempty spectrum")
    real = fsum(m * cos(2 * pi * frequency * float(y))
                for y, m in ordinates.items())
    imag = fsum(-m * sin(2 * pi * frequency * float(y))
                for y, m in ordinates.items())
    return (real * real + imag * imag) / (count * count)


def projection_controls() -> dict[str, object]:
    on_line: Spectrum = ((F(1, 2), F(1)), (F(1, 2), F(-1))) * 2
    off_line: Spectrum = tuple((real, imag)
                              for real in (F(1, 3), F(2, 3))
                              for imag in (F(1), F(-1)))

    for spectrum in (on_line, off_line):
        assert Counter((1 - x, y) for x, y in spectrum) == Counter(spectrum)
        assert Counter((x, -y) for x, y in spectrum) == Counter(spectrum)

    assert all(x == F(1, 2) for x, _ in on_line)
    assert all(x != F(1, 2) for x, _ in off_line)
    assert all(spectral_coordinate(z)[1] == 0 for z in on_line)
    assert all(spectral_coordinate(z)[1] != 0 for z in off_line)

    on_projection = ordinate_measure(on_line)
    off_projection = ordinate_measure(off_line)
    expected = Counter({F(-1): 2, F(1): 2})
    assert on_projection == off_projection == expected
    expected_differences = Counter({F(-2): 4, F(0): 8, F(2): 4})
    assert difference_measure(on_projection) == expected_differences
    assert difference_measure(off_projection) == expected_differences

    samples = []
    for frequency, exact_value in ((F(0), F(1)), (F(1, 8), F(1, 2)),
                                   (F(1, 4), F(0)), (F(1, 2), F(1))):
        measured = intensity(on_projection, float(frequency))
        assert isclose(measured, float(exact_value), rel_tol=1e-13, abs_tol=1e-14)
        assert measured == intensity(off_projection, float(frequency))
        samples.append({"frequency": str(frequency),
                        "normalized_intensity_exact": str(exact_value)})

    # A change to an ordinate changes the data the projection can detect.
    changed = Counter({F(-1): 2, F(1): 1, F(2): 1})
    assert changed != expected
    assert difference_measure(changed) != expected_differences
    assert not isclose(intensity(changed, 0.25), intensity(expected, 0.25),
                       abs_tol=1e-12)

    return {
        "kind": "synthetic spectra; no actual zeta zeros",
        "on_line_spectrum": [[str(x), str(y)] for x, y in on_line],
        "off_line_spectrum": [[str(x), str(y)] for x, y in off_line],
        "ordinate_multiplicities": {str(y): m for y, m in sorted(expected.items())},
        "autocorrelation_coefficients": {
            str(y): m for y, m in sorted(expected_differences.items())},
        "intensity_identity": "I(k) = cos(2*pi*k)^2 for every real k in both models",
        "reason": "the exact projected counting measures agree",
        "full_spectral_coordinate_real_in_on_line_model": True,
        "full_spectral_coordinate_real_in_off_line_model": False,
        "sampled_exact_intensities": samples,
        "changed_ordinate_control_detected": True,
    }


def von_mangoldt_prime_powers(limit: int) -> dict[int, float]:
    """Nonzero Lambda(n), generated by a sieve and prime-power enumeration."""
    if limit < 1:
        raise ValueError("limit must be positive")
    prime = bytearray(b"\x01") * (limit + 1)
    prime[:2] = b"\x00\x00"
    for p in range(2, isqrt(limit) + 1):
        if prime[p]:
            prime[p * p:limit + 1:p] = b"\x00" * ((limit - p * p) // p + 1)
    result = {}
    for p in range(2, limit + 1):
        if prime[p]:
            power = p
            value = log(p)
            while power <= limit:
                assert power not in result
                result[power] = value
                power *= p
    return result


def centered_prime_measure() -> dict[str, object]:
    values = von_mangoldt_prime_powers(max(CHECKPOINTS))
    hand_values = {2: log(2), 3: log(3), 4: log(2), 5: log(5),
                   7: log(7), 8: log(2), 9: log(3)}
    assert {n: value for n, value in values.items() if n <= 10} == hand_values
    assert all(n not in values for n in (1, 6, 10, 12, 30))
    assert values[16] == log(2) and values[27] == log(3) and values[49] == log(7)

    weighted = sorted((n, value / sqrt(n)) for n, value in values.items())
    hand_sum = (log(2) * (1 / sqrt(2) + 1 / 2 + 1 / sqrt(8))
                + log(3) * (1 / sqrt(3) + 1 / 3)
                + log(5) / sqrt(5) + log(7) / sqrt(7))
    assert isclose(fsum(value for n, value in weighted if n <= 10), hand_sum,
                   rel_tol=2e-15, abs_tol=2e-15)

    # Integral of 2*cosh(x/2) on (0, log X] minus the atomic prime mass.
    at_two = 2 * (sqrt(2) - 1 / sqrt(2)) - log(2) / sqrt(2)
    assert isclose(at_two, (2 - log(2)) / sqrt(2), rel_tol=2e-15)
    rows = []
    for cutoff in CHECKPOINTS:
        prime_mass = fsum(value for n, value in weighted if n <= cutoff)
        smooth_mass = 2 * (sqrt(cutoff) - 1 / sqrt(cutoff))
        signed_mass = smooth_mass - prime_mass
        # Atomic and absolutely continuous parts are mutually singular.
        variation = smooth_mass + prime_mass
        assert variation >= abs(signed_mass)
        rows.append({
            "X": cutoff,
            "log_X": log(cutoff),
            "smooth_mass": smooth_mass,
            "weighted_prime_mass": prime_mass,
            "signed_cumulative_A": signed_mass,
            "total_variation_on_positive_interval": variation,
        })

    return {
        "formula": "A(log X) = 2*(sqrt(X)-1/sqrt(X)) - sum(n<=X, Lambda(n)/sqrt(n))",
        "interval": "(0, log X], including a prime-power atom at the upper endpoint",
        "arithmetic": "IEEE-754 double precision with math.fsum",
        "checks": "hand Lambda values through 10, explicit X=2 and X=10 identities",
        "interpretation": "finite illustrations; no asymptotic or temperedness test",
        "checkpoints": rows,
    }


def run() -> dict[str, object]:
    return {
        "status": "PASS",
        "projection_control": projection_controls(),
        "centered_prime_measure": centered_prime_measure(),
    }


if __name__ == "__main__":
    print(json.dumps(run(), indent=2, sort_keys=True))
